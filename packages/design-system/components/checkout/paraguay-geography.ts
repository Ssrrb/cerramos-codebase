const paraguayCountry = {
  id: "country_py",
  isoCode2: "PY",
  isoCode3: "PRY",
  name: "Paraguay",
} as const;

const paraguayStates: ParaguayStateRecord[] = paraguayStateDefinitions.map(
  ({ cities, code, name }) => {
    const stateId = `state_py_${code.toLowerCase()}`;

    return {
      cities: cities.map((cityName) => ({
        id: `city_py_${code.toLowerCase()}_${slugifyParaguayLocation(cityName)}`,
        name: cityName,
        stateId,
      })),
      code,
      countryId: paraguayCountry.id,
      id: stateId,
      name,
    };
  }
);

const paraguayCities = paraguayStates.flatMap((state) => state.cities);

export { paraguayCities, paraguayCountry, paraguayStates };
export type { ParaguayCityRecord, ParaguayStateRecord };
